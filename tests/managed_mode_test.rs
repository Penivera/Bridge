#[test]
fn test_traefik_dynamic_config_generation_and_yaml() {
    let mut routes = HashMap::new();

    // Local route: should be skipped
    let local_node = Node::new("self", "127.0.0.1:80".parse().unwrap());
    routes.insert(
        "local.test".to_string(),
        Route::new(Some("127.0.0.1:8000".parse().unwrap()), local_node),
    );

    // Remote route 1: HTTP on custom port 3000
    let remote_node_1 = Node::new("vm-02", "10.8.0.2:3000".parse().unwrap());
    routes.insert(
        "app.example.com".to_string(),
        Route::new(None, remote_node_1),
    );

    // Remote route 2: HTTPS on port 443
    let remote_node_2 = Node::new("vm-03", "10.8.0.3:443".parse().unwrap());
    routes.insert(
        "secure.example.com".to_string(),
        Route::new(None, remote_node_2),
    );

    let registry = DomainRegistry::with_routes(routes);
    let managed_cfg = ManagedConfig::default()
        .with_local_node_id("self")
        .with_entrypoints(vec!["websecure".to_string()])
        .with_cert_resolver(Some("letsencrypt".to_string()));

    let traefik_config = generate_traefik_config(&registry, RoutingPreference::Mesh, &managed_cfg);

    // Local route must not be present
    assert!(!traefik_config.http.routers.contains_key("bridge-local-test"));
    assert!(!traefik_config.http.services.contains_key("bridge-local-test"));

    // Remote route 1: app.example.com
    let router1 = traefik_config.http.routers.get("bridge-app-example-com").unwrap();
    assert_eq!(router1.rule, "Host(`app.example.com`)");
    assert_eq!(router1.service, "bridge-app-example-com");
    assert_eq!(router1.entry_points, vec!["websecure"]);
    assert_eq!(
        router1.tls.as_ref().unwrap().cert_resolver.as_deref(),
        Some("letsencrypt")
    );

    let svc1 = traefik_config.http.services.get("bridge-app-example-com").unwrap();
    assert_eq!(svc1.load_balancer.servers.len(), 1);
    assert_eq!(svc1.load_balancer.servers[0].url, "http://10.8.0.2:3000");

    // Remote route 2: secure.example.com (port 443 -> https scheme)
    let router2 = traefik_config.http.routers.get("bridge-secure-example-com").unwrap();
    assert_eq!(router2.rule, "Host(`secure.example.com`)");
    let svc2 = traefik_config.http.services.get("bridge-secure-example-com").unwrap();
    assert_eq!(svc2.load_balancer.servers[0].url, "https://10.8.0.3:443");

    // Serialize to YAML and verify structure
    let yaml = traefik_config_to_yaml(&traefik_config).expect("failed to serialize YAML");
    assert!(yaml.contains("# Auto-generated by Bridge daemon in Managed mode"));
    assert!(yaml.contains("Host(`app.example.com`)"));
    assert!(yaml.contains("url: http://10.8.0.2:3000"));
    assert!(yaml.contains("url: https://10.8.0.3:443"));
    assert!(yaml.contains("certResolver: letsencrypt"));
    assert!(yaml.contains("websecure"));
}

